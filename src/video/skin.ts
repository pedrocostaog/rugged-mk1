/**
 * Run the one-time 600ms HUD boot sequence on newly mounted Rugged MK-1 skins.
 */
function initBootSequence(root: Element) {
  if (root.hasAttribute('data-boot')) return;
  const reducedMotion = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
  if (reducedMotion) {
    root.setAttribute('data-boot', 'done');
    return;
  }
  root.setAttribute('data-boot', 'running');
  window.setTimeout(() => {
    root.setAttribute('data-boot', 'done');
  }, 620);
}

if (typeof document !== 'undefined') {
  document.querySelectorAll('.sr-skin').forEach(initBootSequence);
  const observer = new MutationObserver((mutations) => {
    for (const m of mutations) {
      for (const node of m.addedNodes) {
        if (!(node instanceof Element)) continue;
        if (node.classList.contains('sr-skin')) initBootSequence(node);
        node.querySelectorAll('.sr-skin').forEach(initBootSequence);
      }
    }
  });
  observer.observe(document.documentElement, { childList: true, subtree: true });
}
